/*  Хэндл сервы - главная структура API                                     */
/* ------------------------------------------------------------------------ */
/*
 * VESC_Servo_Init() возвращает указатель НА ЭТУ структуру (память
 * статическая, живёт всё время работы программы - хранить у себя, не
 * освобождать). Поля, с которыми предполагается работать СНАРУЖИ:
 *   - vesc                - только чтение, хэндл вески, созданной и
 *                            обслуживаемой этой сервой изнутри (см. шапку
 *                            файла) - команды ему вручную слать не нужно,
 *                            но h->telemetry можно читать напрямую при
 *                            необходимости
 *   - telemetry           - только чтение, готовый снимок состояния сервы
 *                            (см. VESC_Servo_Telemetry_t), обновляется сам
 *   - state, homing_state - только чтение, актуальны в любой момент
 * Остальное - внутреннее состояние (профиль, ПИД, разворачивание угла) -
 * структура объявлена целиком ради простоты (без malloc), но эти поля
 * трогать напрямую не нужно - только через API-функции ниже.
 */
struct VESC_Servo_Handle_s
{
    /* ---- Публичные поля (только чтение) ---- */
    VESC_Handle_t              *vesc;
    VESC_Servo_Telemetry_t      telemetry;
    VESC_Servo_State_t          state;
    VESC_Servo_HomingState_t    homing_state;

    /* ---- Внутреннее состояние - не трогать напрямую ---- */
    uint8_t              used;
    VESC_Servo_Config_t  cfg;

    VESC_Servo_TelemetryCallback_t telemetry_callback; /* см. VESC_Servo_SetTelemetryCallback, NULL по умолчанию */

    uint8_t   wrap_initialized;     /* было ли уже первое чтение pid_pos          */
    float     last_raw_pid_pos_deg; /* последнее СЫРОЕ (0..360) значение pid_pos   */
    float     motor_unwrapped_deg;  /* накопленный угол МОТОРА (до редуктора) - см.
                                      * предупреждение о точности float на очень больших
                                      * пробегах в шапке файла */
    float     output_offset_deg;    /* офсет: output = motor_unwrapped/gear_ratio + offset */

    float     target_deg;           /* заданная конечная цель, град. выходного вала */
    uint8_t   moving;                /* 1 - коррекция сейчас активна (см. гистерезис) */
    float     profile_pos_deg;      /* текущая позиция трапецеидального профиля     */
    float     profile_vel_deg_s;    /* текущая скорость профиля                     */

    float     pid_integral;
    float     last_error_deg;
    uint8_t   has_last_error;

    uint8_t   brake_at_target_enabled; /* см. VESC_Servo_SetBrakeAtTarget, по умолчанию 0 */

    uint8_t   tick_initialized;     /* был ли уже хоть один приход STATUS_4 (для dt)  */
    uint32_t  last_tick;            /* HAL_GetTick() предыдущего прихода STATUS_4     */

    uint32_t  homing_phase_start_tick;
};

/* ------------------------------------------------------------------------ */
/*  Регистрация и опрос состояния                                           */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Регистрирует веску (шина + CAN ID + число полюсов - см. поля
 *         VESC_Servo_Config_t) и серву поверх неё, подписывается на
 *         телеметрию вески - с этого момента контур модуля сам продвигается
 *         по приходу CAN-телеметрии, отдельный тик вызывать не нужно.
 *         Хоуминг НЕ запускается - серва создаётся в VESC_SERVO_STATE_DISABLED.
 * @param  config  заполненная конфигурация (см. VESC_Servo_Config_t)
 * @retval указатель на VESC_Servo_Handle_t (используйте во всех остальных
 *         вызовах), либо NULL при ошибке конфигурации:
 *           - config == NULL;
 *           - не удалось зарегистрировать веску (см. VESC_CAN_Init() в
 *             motor_vesc.h: hcan == NULL, pole_count == 0 либо нечётный,
 *             исчерпаны внутренние пулы motor_vesc, ошибка периферии);
 *           - эта же (hcan, vesc_id) уже обёрнута другой сервой ранее -
 *             колбэк телеметрии на веску только один, второй серве он не
 *             достанется;
 *           - gear_ratio/max_speed_deg_s/max_accel_deg_s2/pid_i_max <= 0;
 *           - limit_switch_pressed_state == VESC_CUSTOM_SENSOR_NONE;
 *           - error_start_correcting_deg <= 0, либо
 *             error_stop_deg вне диапазона [0, error_start_correcting_deg];
 *           - brake_at_target_fraction вне диапазона [0.0, 1.0];
 *           - limit_max_deg <= limit_min_deg;
 *           - working_min_deg/working_max_deg не помещаются целиком внутрь
 *             [limit_min_deg, limit_max_deg], либо working_max_deg <= working_min_deg;
 *           - home_position_deg вне диапазона [limit_min_deg, limit_max_deg];
 *           - исчерпан VESC_SERVO_MAX_SERVOS.
 *         Хоуминг не выполнялся (VESC_SERVO_HOMING_IDLE) - вызовите
 *         VESC_Servo_StartHoming() либо VESC_Servo_SetCurrentPosition(),
 *         прежде чем задавать позицию через VESC_Servo_SetPosition().
 */
VESC_Servo_Handle_t *VESC_Servo_Init(const VESC_Servo_Config_t *config);

/** Текущий угол ВЫХОДНОГО вала, градусы. До первого прихода телеметрии
 *  возвращает 0.0. До успешного хоуминга/калибровки (VESC_Servo_IsHomed()
 *  == 0) значение достоверно только ОТНОСИТЕЛЬНО момента VESC_Servo_Init(),
 *  но не привязано к реальному механическому нулю. Эквивалентно
 *  s->telemetry.position_deg. */
float VESC_Servo_GetPositionDeg(VESC_Servo_Handle_t *s);

/** Заданная в данный момент конечная цель, градусы выходного вала.
 *  Эквивалентно s->telemetry.target_deg. */
float VESC_Servo_GetTargetDeg(VESC_Servo_Handle_t *s);

/** Возвращает указатель на телеметрию сервы. Чисто для удобства/симметрии с
 *  VESC_CAN_GetTelemetry() из motor_vesc - полностью эквивалентно прямому
 *  обращению к s->telemetry.
 * @param  s  хэндл сервы
 * @retval &s->telemetry, либо NULL если s == NULL
 */
const VESC_Servo_Telemetry_t *VESC_Servo_GetTelemetry(VESC_Servo_Handle_t *s);

/** 1 - хоуминг когда-либо успешно завершался (или была ручная калибровка
 *  VESC_Servo_SetCurrentPosition()), т.е. VESC_Servo_GetHomingState() ==
 *  VESC_SERVO_HOMING_DONE; 0 - иначе (в т.ч. если s == NULL). */
uint8_t VESC_Servo_IsHomed(VESC_Servo_Handle_t *s);

/** 1 - серва в VESC_SERVO_STATE_READY и коррекция сейчас НЕ активна
 *  (|target - факт| уже опустилась до error_stop_deg и ниже - см.
 *  VESC_Servo_Config_t); 0 - иначе (в т.ч. если s == NULL). */
uint8_t VESC_Servo_IsAtTarget(VESC_Servo_Handle_t *s);

/** Текущее общее состояние сервы (см. VESC_Servo_State_t). VESC_SERVO_STATE_DISABLED,
 *  если s == NULL. Эквивалентно s->telemetry.state. */
VESC_Servo_State_t VESC_Servo_GetState(VESC_Servo_Handle_t *s);

/** Текущий/последний этап процедуры поиска нуля (см. VESC_Servo_HomingState_t).
 *  VESC_SERVO_HOMING_IDLE, если s == NULL. Эквивалентно s->telemetry.homing_state. */
VESC_Servo_HomingState_t VESC_Servo_GetHomingState(VESC_Servo_Handle_t *s);

/** Мгновенное состояние концевика по последней принятой телеметрии
 *  (telemetry.custom_sensor_state, с учётом limit_switch_pressed_state из
 *  конфига) - 1 значит "нажат". Для отладки/диагностики - сама процедура
 *  хоуминга концевик читает независимо тем же способом. */
uint8_t VESC_Servo_ReadLimitSwitch(VESC_Servo_Handle_t *s);

/** Границы ЗОНЫ ЛИМИТОВ, градусы выходного вала (см. limit_min_deg/
 *  limit_max_deg в VESC_Servo_Config_t) - для удобства, например, если UI
 *  хочет отобразить допустимый диапазон. 0.0, если s == NULL. */
float VESC_Servo_GetLimitMinDeg(VESC_Servo_Handle_t *s);
float VESC_Servo_GetLimitMaxDeg(VESC_Servo_Handle_t *s);

/** Границы РАБОЧЕГО ДИАПАЗОНА, градусы выходного вала (см. working_min_deg/
 *  working_max_deg в VESC_Servo_Config_t и VESC_Servo_SetPositionNormalized()).
 *  0.0, если s == NULL. */
float VESC_Servo_GetWorkingMinDeg(VESC_Servo_Handle_t *s);
float VESC_Servo_GetWorkingMaxDeg(VESC_Servo_Handle_t *s);

/* ------------------------------------------------------------------------ */
/*  Управление                                                              */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Запускает процедуру поиска нуля (см. описание в шапке файла и в
 *         VESC_Servo_HomingState_t). Неблокирующая - сама процедура
 *         продвигается автоматически по приходу телеметрии от вески (см.
 *         событийную модель в шапке файла), прогресс отслеживайте через
 *         VESC_Servo_GetHomingState()/GetState(). Может быть вызвана в
 *         любой момент после VESC_Servo_Init() (не обязательно сразу).
 * @param  s  хэндл сервы
 * @retval HAL_OK - хоуминг запущен; HAL_ERROR - s == NULL, телеметрия вески
 *         не свежая (см. VESC_CAN_IsAlive()/telemetry_timeout_ms), либо от
 *         вески ещё ни разу не приходил кастомный статус с концевиком
 *         (telemetry.rx_mask & VESC_CAN_RXMASK_STATUS_7 == 0) - запускать
 *         хоуминг, не видя концевик, небезопасно.
 */
HAL_StatusTypeDef VESC_Servo_StartHoming(VESC_Servo_Handle_t *s);

/**
 * @brief  Задаёт целевой угол ВЫХОДНОГО вала. Значение автоматически
 *         обрезается по ЗОНЕ ЛИМИТОВ (limit_min_deg/limit_max_deg из
 *         конфига) - выйти за неё через эту функцию невозможно, даже если
 *         передать заведомо некорректное значение. Неблокирующая - отработка
 *         идёт по трапецеидальному профилю автоматически по приходу
 *         телеметрии, запускаясь/останавливаясь по гистерезису (см.
 *         error_start_correcting_deg/error_stop_deg), достижение цели
 *         проверяйте через VESC_Servo_IsAtTarget(). Можно вызывать
 *         повторно в любой момент (в т.ч. до достижения предыдущей цели) -
 *         профиль плавно перестроится на новую цель, не дёргая вал. Именно
 *         так предполагается использовать модуль в цикле - см. README.md.
 *         Если удобнее задавать цель в диапазоне -1.0..1.0 относительно
 *         рабочего диапазона - см. VESC_Servo_SetPositionNormalized().
 * @param  s          хэндл сервы
 * @param  target_deg  целевой угол выходного вала, градусы (система
 *                     координат задаётся в момент хоуминга/калибровки,
 *                     home_position_deg соответствует положению концевика)
 * @retval HAL_OK; HAL_ERROR если s == NULL, либо серва ещё не в
 *         VESC_SERVO_STATE_READY (не хоумлена, отключена, либо в фолте -
 *         см. VESC_Servo_GetState()).
 */
HAL_StatusTypeDef VESC_Servo_SetPosition(VESC_Servo_Handle_t *s, float target_deg);

/**
 * @brief  Задаёт целевой угол ВЫХОДНОГО вала в НОРМАЛИЗОВАННОМ виде
 *         относительно РАБОЧЕГО ДИАПАЗОНА (working_min_deg/working_max_deg
 *         из конфига), а не в градусах напрямую - удобно, когда команду на
 *         серву проще выразить в диапазоне -1..1 (джойстик, слайдер и
 *         т.п.). normalized == -1.0 -> working_min_deg, == 0.0 -> середина
 *         рабочего диапазона, == 1.0 -> working_max_deg. Значения вне
 *         -1.0..1.0 (например -1.2) линейно ЭКСТРАПОЛИРУЮТСЯ за пределы
 *         рабочего диапазона - но итоговый угол всё равно, как и в
 *         VESC_Servo_SetPosition(), обрезается по ЗОНЕ ЛИМИТОВ
 *         (limit_min_deg/limit_max_deg), а не по границам рабочего
 *         диапазона: working-диапазон - это только шкала интерпретации
 *         значения, а не ещё один предел хода. В остальном ведёт себя как
 *         VESC_Servo_SetPosition() (неблокирующая, гистерезис, профиль).
 * @param  s           хэндл сервы
 * @param  normalized  -1.0..1.0 (либо шире - см. выше)
 * @retval HAL_OK; HAL_ERROR если s == NULL, либо серва ещё не в
 *         VESC_SERVO_STATE_READY.
 */
HAL_StatusTypeDef VESC_Servo_SetPositionNormalized(VESC_Servo_Handle_t *s, float normalized);

/**
 * @brief  Ручная калибровка "на лету": говорит модулю "прямо сейчас угол
 *         выходного вала - вот такой", не выполняя физического хоуминга.
 *         Пригодится, если ноль известен из другого источника, либо чтобы
 *         восстановить систему координат после перезапуска МК (сохранив
 *         значение VESC_Servo_GetPositionDeg() во внешнюю энергонезависимую
 *         память самостоятельно и передав его сюда при следующем старте -
 *         ДО первого VESC_Servo_SetPosition()). После вызова серва
 *         переводится в VESC_SERVO_STATE_READY, а хоуминг считается
 *         пройденным (VESC_Servo_IsHomed() == 1), как будто был выполнен
 *         обычным способом.
 *
 *         Если actual_position_deg окажется ЗА пределами зоны лимитов
 *         (limit_min_deg/limit_max_deg) - смещение (output_offset_deg) всё
 *         равно считается от переданного значения (реальный физический
 *         угол, как он есть), но заданная цель обрезается по зоне лимитов -
 *         то есть контур сразу начнёт корректировать вал обратно внутрь
 *         зоны, а не останется стоять снаружи (см. подробности про зону
 *         лимитов в шапке файла).
 * @param  s                    хэндл сервы
 * @param  actual_position_deg  реальный угол выходного вала прямо сейчас, градусы
 * @retval HAL_OK; HAL_ERROR если s == NULL, либо ещё ни разу не приходила
 *         телеметрия вески (не от чего считать офсет - подождите первый
 *         приход телеметрии после появления связи с веской)
 */
HAL_StatusTypeDef VESC_Servo_SetCurrentPosition(VESC_Servo_Handle_t *s, float actual_position_deg);

/**
 * @brief  Включает контур позиции после VESC_Servo_Disable() БЕЗ повторного
 *         хоуминга - продолжает от текущей фактической позиции (профиль и
 *         цель сбрасываются на неё же, рывка не будет; коррекция изначально
 *         не активна, т.к. ошибка на этот момент равна 0).
 * @param  s  хэндл сервы
 * @retval HAL_OK; HAL_ERROR если s == NULL, либо хоуминг/калибровка ни разу
 *         не выполнялись (VESC_Servo_IsHomed() == 0) - в этом случае нужен
 *         VESC_Servo_StartHoming() или VESC_Servo_SetCurrentPosition().
 */
HAL_StatusTypeDef VESC_Servo_Enable(VESC_Servo_Handle_t *s);

/**
 * @brief  Немедленно останавливает мотор (Brake = 0, т.е. свободное
 *         вращение вала, без активного удержания) и переводит серву в
 *         VESC_SERVO_STATE_DISABLED. Контур позиции не считается, пока не
 *         будет вызван VESC_Servo_Enable(). Прошедший ранее хоуминг НЕ
 *         сбрасывается - VESC_Servo_IsHomed() останется 1. Разворачивание
 *         угла мотора продолжает работать и в DISABLED (см. шапку файла).
 * @param  s  хэндл сервы
 * @retval HAL_OK; HAL_ERROR если s == NULL
 */
HAL_StatusTypeDef VESC_Servo_Disable(VESC_Servo_Handle_t *s);

/**
 * @brief  Включает/выключает удержание вала тормозным током вески, пока
 *         коррекция остановлена гистерезисом (см. error_stop_deg) - то
 *         есть пока серва считает, что она "на месте". Нужно, чтобы
 *         вибрация/внешняя нагрузка не сместили ось в паузах между
 *         командами скорости. Сила тормоза задаётся в конфиге
 *         (brake_at_target_fraction, доля от макс. тока вески). По
 *         умолчанию (сразу после VESC_Servo_Init) - ВЫКЛЮЧЕНО, то есть в
 *         паузах отправляется просто скорость 0 (аналогично
 *         VESC_CAN_SetSimulated - переключатель поведения, отдельный от
 *         основного конфига).
 * @param  s        хэндл сервы
 * @param  enabled  1 - тормозить в цели заданной в конфиге силой, 0 - слать
 *                  скорость 0 (без активного удержания)
 * @retval HAL_OK; HAL_ERROR если s == NULL
 */
HAL_StatusTypeDef VESC_Servo_SetBrakeAtTarget(VESC_Servo_Handle_t *s, uint8_t enabled);

/**
 * @brief  Задаёт (или снимает, если callback == NULL) обработчик, который
 *         будет вызван при получении КАЖДОГО распознанного статусного
 *         пакета телеметрии вески этой сервы - см. подробное объяснение и
 *         предупреждение об ISR-контексте в шапке файла и у
 *         VESC_Servo_TelemetryCallback_t.
 * @param  s         хэндл сервы
 * @param  callback  функция-обработчик (см. VESC_Servo_TelemetryCallback_t),
 *                    либо NULL чтобы отключить
 * @retval HAL_OK; HAL_ERROR если s == NULL
 */
HAL_StatusTypeDef VESC_Servo_SetTelemetryCallback(VESC_Servo_Handle_t *s, VESC_Servo_TelemetryCallback_t callback);

/**
 * @brief  Необязательная диагностическая функция - проверяет, не пропала ли
 *         телеметрия от вески дольше telemetry_timeout_ms (см.
 *         VESC_CAN_IsAlive()), и если да - останавливает мотор (Brake = 0)
 *         и переводит серву в VESC_SERVO_STATE_FAULT. Нужна ТОЛЬКО для
 *         полной тишины на шине - см. подробное объяснение в шапке файла
 *         про пределы событийной модели. Контур позиции в вызове НЕ
 *         нуждается для своей нормальной работы - он и так продвигается
 *         автоматически по приходу телеметрии; вызывайте эту функцию
 *         изредка (например раз в секунду) из любого своего периодического
 *         места, если вам важно, чтобы VESC_Servo_GetState() достоверно
 *         отражал полную потерю связи, либо не вызывайте вовсе и
 *         полагайтесь на штатный таймаут потери команд самой вески.
 * @param  s  хэндл сервы
 */
void VESC_Servo_CheckAlive(VESC_Servo_Handle_t *s);

