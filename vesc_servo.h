/*  Хэндл сервы - главная структура API                                     */
/* ------------------------------------------------------------------------ */
/*
 * VESC_Servo_Init() возвращает указатель НА ЭТУ структуру (память
 * статическая, живёт всё время работы программы - хранить у себя, не
 * освобождать). Поля, с которыми предполагается работать СНАРУЖИ:
 *   - vesc                - только чтение, хэндл вески, созданной и
 *                            обслуживаемой этой сервой изнутри (см. шапку
 *                            файла) - команды ему вручную слать не нужно,
 *                            но h->telemetry можно читать напрямую при
 *                            необходимости
 *   - telemetry           - только чтение, готовый снимок состояния сервы
 *                            (см. VESC_Servo_Telemetry_t), обновляется сам
 *   - state, homing_state - только чтение, актуальны в любой момент
 * Остальное - внутреннее состояние (профиль, ПИД, разворачивание угла) -
 * структура объявлена целиком ради простоты (без malloc), но эти поля
 * трогать напрямую не нужно - только через API-функции ниже.
 */
struct VESC_Servo_Handle_s
{
    /* ---- Публичные поля (только чтение) ---- */
    VESC_Handle_t              *vesc;
    VESC_Servo_Telemetry_t      telemetry;
    VESC_Servo_State_t          state;
    VESC_Servo_HomingState_t    homing_state;

    /* ---- Внутреннее состояние - не трогать напрямую ---- */
    uint8_t              used;
    VESC_Servo_Config_t  cfg;

    /* Кэш величин, производных от cfg (которая не меняется после
     * VESC_Servo_Init() - сеттера для неё нет) - посчитаны один раз при
     * инициализации, чтобы в горячем пути (вызывается на каждый приход
     * STATUS_4, из ISR) не повторять одно и то же деление на каждом тике.
     * См. их использование в vesc_servo.c. */
    float     inv_gear_ratio;      /* 1 / cfg.gear_ratio */
    float     motor_rpm_per_deg_s; /* cfg.gear_ratio / 6 */
    float     inv_2_max_accel;     /* 1 / (2 * cfg.max_accel_deg_s2) */
    float     pid_integral_max;    /* cfg.pid_i_max / |cfg.pid_ki| */
    float     max_step_dt_s;       /* cfg.max_step_dt_ms / 1000 */

    VESC_Servo_TelemetryCallback_t telemetry_callback; /* см. VESC_Servo_SetTelemetryCallback, NULL по умолчанию */

    uint8_t   wrap_initialized;     /* было ли уже первое чтение pid_pos          */
    float     last_raw_pid_pos_deg; /* последнее СЫРОЕ (0..360) значение pid_pos   */
    float     motor_unwrapped_deg;  /* накопленный угол МОТОРА (до редуктора) - см.
                                      * предупреждение о точности float на очень больших
                                      * пробегах в шапке файла */
    float     output_offset_deg;    /* офсет: output = motor_unwrapped/gear_ratio + offset */

    float     target_deg;           /* заданная конечная цель, град. выходного вала */
    uint8_t   moving;               /* 1 - коррекция сейчас активна (см. гистерезис) */
    float     profile_pos_deg;      /* текущая позиция трапецеидального профиля     */
    float     profile_vel_deg_s;    /* текущая скорость профиля                     */

    float     pid_integral;
    float     last_error_deg;
    uint8_t   has_last_error;

    uint8_t   brake_at_target_enabled; /* см. VESC_Servo_SetBrakeAtTarget, по умолчанию 0 */

    uint8_t   tick_initialized;     /* был ли уже хоть один приход STATUS_4 (для dt и
                                      * для vesc_servo_telemetry_fresh - см. .c)       */
    uint32_t  last_tick;            /* HAL_GetTick() предыдущего прихода STATUS_4     */

    uint8_t   status7_initialized;  /* был ли уже хоть один приход STATUS_7 (концевик) */
    uint32_t  last_status7_tick;    /* HAL_GetTick() последнего прихода STATUS_7 - см.
                                      * vesc_servo_limit_switch_fresh() в .c: rx_mask у
                                      * motor_vesc "хотя бы раз" не значит "недавно"    */

    uint32_t  homing_phase_start_tick;
};

